"""scripts/check_arch_wheels.py: which pins the index cannot install on each architecture."""

import importlib.util
import sys
import urllib.error
from pathlib import Path

import pytest

_SPEC = importlib.util.spec_from_file_location(
    "check_arch_wheels", Path(__file__).resolve().parents[1] / "scripts" / "check_arch_wheels.py"
)
caw = importlib.util.module_from_spec(_SPEC)
sys.modules[_SPEC.name] = caw
_SPEC.loader.exec_module(caw)

INDEX = "https://index.test/simple/"
ARCHES = ("x86_64", "ppc64le", "s390x")


def _fake_index(files: dict[str, list[str]]):
    def fetch(index, name):
        assert index == INDEX
        if name not in files:
            raise urllib.error.HTTPError(f"{index}{name}/", 404, "Not Found", None, None)
        return files[name]

    return fetch


def _missing(filenames, version="1.0", arches=ARCHES, python="3.12"):
    pin = caw.Pin("pkg", version, 1)
    wanted = {arch: caw.supported_tags(arch, python) for arch in arches}
    return caw.missing_arches(filenames, pin, wanted)


def test_parse_requirements_reads_the_index_and_pins_with_their_lines():
    text = (
        "# This file was autogenerated by uv\n"
        f"--index-url {INDEX}\n"
        "\n"
        "garak==0.17.0+rhaiv.4\n"
        "    # via llama-stack-provider-trustyai-garak\n"
        "torch[cpu]==2.13.0\n"
        "something>=1.0\n"
        "triton==3.6.0 ; platform_machine != 's390x'\n"
    )
    index, pins, unpinned = caw.parse_requirements(text)
    assert index == INDEX
    assert pins == [
        caw.Pin("garak", "0.17.0+rhaiv.4", 4),
        caw.Pin("torch", "2.13.0", 6),
        caw.Pin("triton", "3.6.0", 8, "platform_machine != 's390x'"),
    ]
    assert unpinned == [(7, "something>=1.0")]


def test_markers_select_the_architectures_that_install_a_pin():
    triton = caw.Pin("triton", "3.6.0", 1, "platform_machine != 's390x'")
    hf_xet = caw.Pin(
        "hf-xet",
        "1.6.0",
        2,
        "platform_machine == 'AMD64' or platform_machine == 'aarch64' or platform_machine == 'x86_64'",
    )
    linux_only = caw.Pin("python-magic", "0.4.27", 3, "sys_platform != 'win32'")
    assert caw.needed_on(triton, ARCHES, "3.12") == ["x86_64", "ppc64le"]
    assert caw.needed_on(hf_xet, ARCHES, "3.12") == ["x86_64"]
    assert caw.needed_on(linux_only, ARCHES, "3.12") == list(ARCHES)
    assert caw.needed_on(caw.Pin("pkg", "1.0", 4), ARCHES, "3.12") == list(ARCHES)


def test_one_wheel_per_architecture_covers_all():
    files = [f"pkg-1.0-1-cp312-cp312-linux_{arch}.whl" for arch in ARCHES]
    assert _missing(files) == []


def test_a_missing_architecture_is_reported():
    files = ["pkg-1.0-1-cp312-cp312-linux_x86_64.whl", "pkg-1.0-1-cp312-cp312-linux_s390x.whl"]
    assert _missing(files) == ["ppc64le"]


def test_pure_python_and_abi3_wheels_cover_every_architecture():
    assert _missing(["pkg-1.0-py3-none-any.whl"]) == []
    assert _missing([f"pkg-1.0-cp310-abi3-linux_{arch}.whl" for arch in ARCHES]) == []


def test_manylinux_tags_count_up_to_the_rhel9_glibc():
    assert _missing(["pkg-1.0-cp312-cp312-manylinux_2_28_s390x.whl"], arches=("s390x",)) == []
    assert _missing(["pkg-1.0-cp312-cp312-manylinux2014_ppc64le.whl"], arches=("ppc64le",)) == []
    assert _missing(["pkg-1.0-cp312-cp312-manylinux_2_39_s390x.whl"], arches=("s390x",)) == ["s390x"]


def test_wheels_for_another_python_or_version_do_not_count():
    assert _missing([f"pkg-1.0-cp313-cp313-linux_{arch}.whl" for arch in ARCHES]) == list(ARCHES)
    assert _missing([f"pkg-1.1-cp312-cp312-linux_{arch}.whl" for arch in ARCHES]) == list(ARCHES)
    assert _missing(["pkg-1.0.tar.gz"]) == list(ARCHES)


def test_versions_compare_as_versions_with_local_labels():
    files = ["garak-0.17.0+rhaiv.4-py3-none-any.whl"]
    pin = caw.Pin("garak", "0.17.0+rhaiv.4", 1)
    wanted = {arch: caw.supported_tags(arch, "3.12") for arch in ARCHES}
    assert caw.missing_arches(files, pin, wanted) == []
    assert caw.missing_arches(["pkg-1.0.0-py3-none-any.whl"], caw.Pin("pkg", "1.0", 1), wanted) == []


def test_check_reports_missing_unknown_and_absent_packages():
    files = {
        "complete": [f"complete-2.0-cp312-cp312-linux_{arch}.whl" for arch in ARCHES],
        "partial": ["partial-3.0-cp312-cp312-linux_x86_64.whl"],
    }
    pins = [caw.Pin("complete", "2.0", 1), caw.Pin("partial", "3.0", 2), caw.Pin("absent", "1.0", 3)]
    results = {r.pin.name: r for r in caw.check(INDEX, pins, ARCHES, "3.12", fetch=_fake_index(files))}
    assert results["complete"].missing == [] and results["complete"].error is None
    assert results["partial"].missing == ["ppc64le", "s390x"]
    assert results["absent"].missing == list(ARCHES) and results["absent"].error == "not on the index"


def test_a_pin_is_only_checked_where_its_marker_installs_it():
    files = {"triton": ["triton-3.6.0-cp312-cp312-linux_x86_64.whl", "triton-3.6.0-cp312-cp312-linux_ppc64le.whl"]}
    needed = caw.Pin("triton", "3.6.0", 1, "platform_machine != 's390x'")
    everywhere = caw.Pin("triton", "3.6.0", 1)
    (result,) = caw.check(INDEX, [needed], ARCHES, "3.12", fetch=_fake_index(files))
    assert result.needed_on == ["x86_64", "ppc64le"] and result.missing == []
    (result,) = caw.check(INDEX, [everywhere], ARCHES, "3.12", fetch=_fake_index(files))
    assert result.missing == ["s390x"]


def test_a_pin_no_architecture_installs_is_not_looked_up():
    def unreachable(index, name):
        raise AssertionError("looked up a pin no target installs")

    (result,) = caw.check(
        INDEX, [caw.Pin("pywin32", "311", 1, "sys_platform == 'win32'")], ARCHES, "3.12", fetch=unreachable
    )
    assert result.needed_on == [] and result.missing == [] and result.error is None


def test_an_unreadable_index_is_not_reported_as_available():
    def broken(index, name):
        raise urllib.error.HTTPError(index, 503, "Service Unavailable", None, None)

    (result,) = caw.check(INDEX, [caw.Pin("pkg", "1.0", 1)], ARCHES, "3.12", fetch=broken)
    assert result.missing == [] and result.error == "index answered HTTP 503"


@pytest.mark.parametrize(
    ("files", "status"),
    [
        ({"pkg": [f"pkg-1.0-cp312-cp312-linux_{a}.whl" for a in ARCHES]}, 0),
        ({"pkg": ["pkg-1.0-cp312-cp312-linux_x86_64.whl"]}, 1),
    ],
)
def test_main_exit_status(tmp_path, monkeypatch, capsys, files, status):
    requirements = tmp_path / "requirements.txt"
    requirements.write_text(f"--index-url {INDEX}\npkg==1.0\n")
    monkeypatch.setattr(caw, "fetch_files", _fake_index(files))
    assert caw.main([str(requirements), "--no-resolve"]) == status
    out = capsys.readouterr().out
    assert ("MISSING pkg==1.0: no installable wheel for ppc64le, s390x" in out) == (status == 1)


def test_main_needs_an_index(tmp_path):
    requirements = tmp_path / "requirements.txt"
    requirements.write_text("pkg==1.0\n")
    assert caw.main([str(requirements)]) == 2


def _lock(tmp_path):
    requirements = tmp_path / "requirements.txt"
    requirements.write_text(f"--index-url {INDEX}\n\npkg==1.0\n    # via x\ntriton==3.6.0\n")
    return requirements


def test_main_takes_markers_from_the_resolution_and_lines_from_the_lock(tmp_path, monkeypatch, capsys):
    files = {
        "pkg": [f"pkg-1.0-cp312-cp312-linux_{a}.whl" for a in ARCHES],
        "triton": ["triton-3.6.0-cp312-cp312-linux_x86_64.whl"],
    }
    resolved = f"--index-url {INDEX}\ntriton==3.6.0 ; platform_machine != 's390x'\npkg==1.0\n"
    monkeypatch.setattr(caw, "fetch_files", _fake_index(files))
    monkeypatch.setattr(caw, "resolve_with_markers", lambda lock, index, python: resolved)
    monkeypatch.setenv("GITHUB_ACTIONS", "true")
    assert caw.main([str(_lock(tmp_path))]) == 1
    out = capsys.readouterr().out
    assert "not installed on s390x (environment marker): triton" in out
    assert "MISSING triton==3.6.0: no installable wheel for ppc64le" in out
    assert "line=5::triton==3.6.0" in out  # the lock's line, not the resolution's


def test_main_refuses_a_resolution_that_differs_from_the_lock(tmp_path, monkeypatch, capsys):
    monkeypatch.setattr(caw, "resolve_with_markers", lambda lock, index, python: f"--index-url {INDEX}\npkg==1.1\n")
    assert caw.main([str(_lock(tmp_path))]) == 2
    assert "gave different pins" in capsys.readouterr().out
